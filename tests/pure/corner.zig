test "real CALayer continuous corner masks measure within 0.15pt" {
    var buffer_1x: [48 * 48]u8 = @splat(255);
    for (0..22) |row| {
        for (0..22) |column| {
            buffer_1x[row * 48 + column] = calayer_radius_16[row][column];
        }
    }
    const measured_1x = huen_corner_radius(&buffer_1x, 48, 48, 48.0);
    try std.testing.expectApproxEqAbs(16.0, measured_1x, 0.15);

    var buffer_2x: [96 * 96]u8 = @splat(255);
    for (calayer_radius_26_2x, 0..) |prefix, row| {
        @memcpy(buffer_2x[row * 96 .. row * 96 + prefix.len], prefix);
    }
    const measured_2x = huen_corner_radius(&buffer_2x, 96, 96, 48.0);
    try std.testing.expectApproxEqAbs(26.0, measured_2x, 0.15);
}

test "translucent window with opaque pixels on interior edges keeps accurate radius" {
    var calayer_translucent: [48 * 48]u8 = @splat(153);
    for (0..22) |row| {
        for (0..22) |column| {
            const scaled = @as(f64, @floatFromInt(calayer_radius_16[row][column])) * 0.6;
            calayer_translucent[row * 48 + column] = @intFromFloat(@round(scaled));
        }
    }
    // Opaque text-like patch covering the bottom-right pixel and part of the last row and column.
    for (36..48) |row| {
        for (36..48) |column| {
            calayer_translucent[row * 48 + column] = 255;
        }
    }
    const measured_calayer = huen_corner_radius(&calayer_translucent, 48, 48, 48.0);
    try std.testing.expectApproxEqAbs(16.0, measured_calayer, 0.15);
}

test "square corners return zero and invalid or transparent buffers return -1" {
    const opaque_square: [48 * 48]u8 = @splat(255);
    try std.testing.expectEqual(@as(f64, 0.0), huen_corner_radius(&opaque_square, 48, 48, 48.0));

    const dim_square: [48 * 48]u8 = @splat(32);
    try std.testing.expectEqual(@as(f64, 0.0), huen_corner_radius(&dim_square, 48, 48, 48.0));

    const transparent: [48 * 48]u8 = @splat(0);
    try std.testing.expectEqual(@as(f64, -1.0), huen_corner_radius(&transparent, 48, 48, 48.0));

    const faint: [48 * 48]u8 = @splat(31);
    try std.testing.expectEqual(@as(f64, -1.0), huen_corner_radius(&faint, 48, 48, 48.0));

    try std.testing.expectEqual(@as(f64, -1.0), huen_corner_radius(null, 48, 48, 48.0));
    try std.testing.expectEqual(@as(f64, -1.0), huen_corner_radius(&opaque_square, 1, 48, 48.0));
    try std.testing.expectEqual(@as(f64, -1.0), huen_corner_radius(&opaque_square, 48, 1, 48.0));
    try std.testing.expectEqual(@as(f64, -1.0), huen_corner_radius(&opaque_square, 48, 48, 0.0));
    try std.testing.expectEqual(@as(f64, -1.0), huen_corner_radius(&opaque_square, 48, 48, -48.0));
    try std.testing.expectEqual(@as(f64, -1.0), huen_corner_radius(&opaque_square, 48, 48, std.math.inf(f64)));
    try std.testing.expectEqual(@as(f64, -1.0), huen_corner_radius(&opaque_square, 48, 48, -std.math.inf(f64)));
    try std.testing.expectEqual(@as(f64, -1.0), huen_corner_radius(&opaque_square, 48, 48, std.math.nan(f64)));
}
